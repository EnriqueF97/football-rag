"""The golden set: schema, loading, and validation.

The golden set is the measuring instrument of this project — ~150 hand-written questions
with reference answers **and annotated relevant document ids**. That third field is what
lets retrieval be scored independently of generation; without it you only ever get a
single end-to-end number that cannot say which half failed.

It is the one data artefact committed to git: our own questions and judgements, never
article text. The annotation guideline ships beside it in
``data/golden/RELEVANCE_RUBRIC.md`` — labels are uninterpretable without the rule that
produced them, so this module's validation exists to enforce that rubric mechanically.

One item on disk (one JSON object per line)::

    {
      "id": "q0001",
      "type": "causal",
      "question": "Why did Club X dismiss their manager in March 2025?",
      "reference_answer": "Six games without a win and a board dispute over transfers.",
      "relevant_docs": [{"doc_id": 4471, "level": 2}, {"doc_id": 4488, "level": 1}],
      "as_of": null,
      "difficulty": null,
      "source_doc_id": 4471,
      "drafted_by": "llm",
      "reviewed_by": "human",
      "notes": "",
      "created_at": "2026-09-14"
    }

Schema decisions, each with its reason:

* **Only levels 1 and 2 are stored.** Absence means 0 — storing every irrelevant document
  would mean ~25,000 entries per question.
* **Documents, not chunks.** Retrieval returns chunks; the scorer maps each chunk back to
  its ``article_id``. Annotating at document level keeps the golden set stable across
  chunking strategies, which matters because chunking is an ablation axis.
* **``source_doc_id``** records the document the question was written *from*. Questions
  are generated by reading the corpus, never from memory, so every question is answerable
  by construction; this field is the audit trail for that claim.
* **``drafted_by``** is honest provenance: an LLM may draft a question, but a human
  reviews and owns every item. Recorded, not hidden.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path

DEFAULT_PATH = Path("data/golden/golden_set.jsonl")

#: Question taxonomy, agreed 2026-09-14. Keys are the legal values of `GoldenItem.type`.
QUESTION_TYPES = {
    "factual": "Simple fact stated in the corpus. The retrieval baseline.",
    "causal": "Why/how something happened — text-native, needs prose, not a table.",
    "temporal": "Answer depends on when you ask; requires `as_of`.",
    "multi_doc": "No single document holds the whole answer; forces synthesis.",
    "contradictory": "Outlets disagree; the disagreement is part of the answer.",
    "unanswerable": "The corpus cannot support an answer. Measures abstention.",
}

#: Approximate target shares of the ~150 items.
TARGET_MIX = {
    "factual": 0.20,
    "causal": 0.20,
    "temporal": 0.15,
    "contradictory": 0.15,
    "multi_doc": 0.20,
    "unanswerable": 0.10,
}


@dataclass
class GoldenItem:
    """One question in the golden set. Field order matches the JSON on disk."""

    id: str
    type: str
    question: str
    reference_answer: str
    relevant_docs: list[dict]  # [{"doc_id": int, "level": 1|2}]
    as_of: str | None = None  # YYYY-MM-DD, required when type == "temporal"
    difficulty: str | None = None  # optional: "easy" | "medium" | "hard"
    source_doc_id: int | None = None  # the document the question was written from
    drafted_by: str = "human"  # "human" | "llm"
    reviewed_by: str = "human"
    notes: str = ""
    created_at: str = ""

    def doc_ids(self) -> list[int]:
        """Every annotated document id, regardless of level.

        Used by recall@k: "did retrieval return any of the documents I marked?"

        Expected: for the example above -> [4471, 4488]
        """
        return [d["doc_id"] for d in self.relevant_docs]

    def level2_ids(self) -> list[int]:
        """Only the ids marked level 2 (a single document that fully answers).

        Used for the stricter variant of the metric, and to check that a non-multi_doc
        question has at least one sufficient document.

        Expected: for the example above -> [4471]   (4488 is level 1, so excluded)
        """
        return [d["doc_id"] for d in self.relevant_docs if d["level"] == 2]


@dataclass
class ValidationReport:
    """Outcome of `validate`. Errors block use of the set; warnings are advisory."""

    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        """True when the set is usable — i.e. no errors. Warnings do not block.

        Expected: errors=[] -> True   ·   errors=["..."] -> False   (warnings ignored)
        """
        return not self.errors


def load(path: str | Path = DEFAULT_PATH) -> list[GoldenItem]:
    """Read the golden set from a JSONL file.

    Returns an empty list if the file does not exist yet (the set is built incrementally,
    so "not there yet" is normal and not an error).

    Raises `ValueError` on a malformed line, with the file and line number — a silently
    skipped line would quietly shrink the measuring instrument, and we would never notice.

    Args:
        path: JSONL file, one item per line.
    Returns:
        The items, in file order.

    Expected:
        file missing            -> []
        two good lines          -> [GoldenItem(...), GoldenItem(...)]
        line 7 is broken JSON   -> ValueError("data/golden/golden_set.jsonl:7: ...")
    """
    path = Path(path)
    if not path.exists():
        return []

    items: list[GoldenItem] = []
    # 1-based counter so error messages match what an editor shows.
    for n, line in enumerate(path.read_text().splitlines(), 1):
        # A trailing newline is not a parse failure.
        if not line.strip():
            continue

        try:
            data = json.loads(line)
            golden_item = GoldenItem(**data)
        except (json.JSONDecodeError, TypeError) as exc:
            raise ValueError(f"{path}:{n}: {exc}") from exc

        items.append(golden_item)

    return items


def validate(items: list[GoldenItem], conn=None) -> ValidationReport:
    """Check the rubric's mechanical rules over a whole golden set.

    These are the rules that are cheap to get wrong by hand and expensive to discover
    later, once numbers have been published.

    Error vs warning — the distinction matters:
      * **error**   = the set is wrong and any metric computed from it would be invalid.
      * **warning** = suspicious, probably a mistake, but a deliberate choice is possible.

    Args:
        items: the loaded golden set.
        conn:  optional corpus DB connection. When given, also runs the checks that need
               the corpus (see `_check_docs`). Without it, only the self-contained rules
               run — so the function is useful in tests with no database.
    Returns:
        A ValidationReport.

    Expected, for a set with one bad item:
        rep.ok        -> False
        rep.errors    -> ["[q3] temporal questions require `as_of`"]
        rep.warnings  -> ["[q5] doc 17 has near-duplicate twins not annotated: [27, 30]"]
    """
    rep = ValidationReport()
    seen_ids: set[str] = set()

    for it in items:
        where = f"[{it.id}]"  # prefix every message so a failure is findable

        # --- 1. Identity and basic shape ---------------------------------------------
        if it.id in seen_ids:
            rep.errors.append(f"{where} duplicate question id")
        seen_ids.add(it.id)

        if it.type not in QUESTION_TYPES:
            rep.errors.append(f"{where} unknown type {it.type!r}")

        if not it.question.strip():
            rep.errors.append(f"{where} empty question")

        # --- 2. Relevance levels -----------------------------------------------------
        levels = [doc["level"] for doc in it.relevant_docs]

        # --- 3. Answerable vs unanswerable -------------------------------------------
        if it.type == "unanswerable":
            if it.relevant_docs:
                rep.errors.append(
                    f"{where} relevant documents detected in unanswerable question, it should not have any relevant docs"
                )
            if it.reference_answer.strip():
                rep.warnings.append(
                    f"{where} reference_answer detected in unanswerable question, it is supposed to be unanswerable"
                )

        else:
            if not it.relevant_docs:
                rep.errors.append(
                    f"{where} no relevant documents detected, should it be answerable?"
                )
            if not it.reference_answer.strip():
                rep.errors.append(
                    f"{where} no reference answer detected, it is required for answerable question"
                )
            # multi_doc is exempt: by definition no single document suffices.
            if 2 not in levels and it.type != "multi_doc":
                rep.warnings.append(
                    f"{where} no level 2 relevant documents detected, is this a multi_doc question?"
                )

        if any(lv not in (1, 2) for lv in levels):
            rep.errors.append(
                f"{where} illegal relevance level in relevant_docs — only 1 and 2 are "
                f"stored, 0 is expressed by absence"
            )

        # --- 4. Temporal questions ---------------------------------------------------
        if it.type == "temporal" and it.as_of is None:
            rep.errors.append(
                f"{where} no as_of date detected in temporal question, date is required"
            )
        if it.type != "temporal" and it.as_of is not None:
            rep.warnings.append(
                f"{where} as_of date detected in no temporal question, probably wrong type"
            )

        # --- 5. Corpus-backed checks -------------------------------------------------
        if conn is not None:
            _check_docs(conn, it, rep)

    return rep


def _check_docs(conn, it: GoldenItem, rep: ValidationReport) -> None:
    """Corpus-backed checks for one item. Appends to `rep` in place.

    Only the usable corpus (``body_valid = 1 AND dup_of IS NULL``) is ever indexed, so a
    near-duplicate can never be retrieved. Annotating one is therefore a silent failure:
    the document is unreachable, the hit never happens, and recall@k is depressed equally
    across every configuration — the ablation table stays internally consistent and is
    uniformly wrong. Hence the near-duplicate check is an error, not a warning.

    Args:
        conn: open corpus DB connection.
        it:   the item to check.
        rep:  report to append messages to.

    Expected:
        doc id not in the corpus -> errors   += ["[q4] doc 999 does not exist"]
        doc is a near-duplicate  -> errors   += ["[q4] doc 27 is a near-duplicate of 17 …"]
        body_valid = 0           -> warnings += ["[q4] doc 32 has no valid body …"]
    """
    where = f"[{it.id}]"

    # Every annotated document must exist, be canonical, and be usable.
    for doc_id in it.doc_ids():
        row = conn.execute(
            "SELECT body_valid, dup_of FROM articles WHERE id = ?", (doc_id,)
        ).fetchone()

        if row is None:
            rep.errors.append(f"{where} doc {doc_id} does not exist in the corpus")
            continue

        body_valid, dup_of = row

        if dup_of is not None:
            rep.errors.append(
                f"{where} doc {doc_id} is a near-duplicate of {dup_of}; annotate the "
                f"canonical document instead"
            )
        if not body_valid:
            rep.warnings.append(
                f"{where} doc {doc_id} has no valid body, so retrieval can never "
                f"return it and recall@k is capped below 1.0"
            )

